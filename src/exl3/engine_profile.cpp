void apply_engine_profile() {
    static std::once_flag once;
    std::call_once(once, [] {
        for (const auto& [name, value] : kProfile) {
            // An empty value counts as unset (shells leave empty variables behind when clearing).
            if (const char* set = std::getenv(name); set != nullptr && *set != '\0') continue;
#ifdef _WIN32
            _putenv_s(name, value);
#else
            setenv(name, value, 0);
#endif
        }
    });
}
